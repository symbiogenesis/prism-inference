//! Bounded ordinary-text boundaries for the pinned Qwen3.5 pretokenizer.
//!
//! Scanner and category data follow PrismML-Eng/llama.cpp revision
//! `73bfe6cc485554822f80c473a3c0c4f25e80f41b`, specifically
//! `unicode_regex_split_custom_qwen35` in `src/unicode.cpp` (SHA-256
//! `b1f3a18646197e21f7300c6d3b45c9faf52a123d58a38d7d54f3f225018da45d`)
//! and `src/unicode-data.cpp` (SHA-256
//! `95170cd1c105a5b41a1b2dce73b0fae8ce8011ef7897600828bb2babe8b26e5d`).
//! The ported scanner/data retain their MIT terms in
//! [PRISM-LICENSE.txt](../PRISM-LICENSE.txt).
//!
//! These boundaries implement the pinned runtime's custom scanner, including
//! its Unicode combining-mark letter runs and whitespace backtracking. Unicode
//! properties are pinned data, independent of Rust's Unicode version. Special
//! token recognition, token insertion and chat templates are separate policies.

use bonsai_gguf::Metadata;

use crate::bpe::{MAX_BPE_INPUT_BYTES, MAX_BPE_INPUT_PIECES, MAX_BPE_PIECE_BYTES};
use crate::{Result, invalid};

const LETTER_OR_MARK: u8 = 1;
const NUMBER: u8 = 2;

/// Validated `gpt2` / `qwen35` ordinary-text boundary scanner.
///
/// Construction requires an explicit model declaration. It does not inspect
/// vocabulary/merge arrays or implement model-declared special-token policies.
#[derive(Clone, Copy, Debug)]
pub struct Qwen35PreTokenizer {
    _validated: (),
}

/// Checked ordinary-text pieces borrowed from the original UTF-8 input.
///
/// Each item validates its byte and piece bounds before yielding a nonempty
/// slice. Fully consuming the iterator validates the entire input. After an
/// error it yields no further items. Scanning uses constant scratch space.
pub struct Qwen35Pieces<'a> {
    remaining: &'a str,
    emitted: usize,
}

impl Qwen35PreTokenizer {
    /// Requires exact string metadata `tokenizer.ggml.model = "gpt2"` and
    /// `tokenizer.ggml.pre = "qwen35"`.
    ///
    /// # Errors
    /// Rejects missing, mistyped or unsupported tokenizer declarations.
    pub fn from_metadata(metadata: &Metadata) -> Result<Self> {
        for (key, required) in [
            ("tokenizer.ggml.model", "gpt2"),
            ("tokenizer.ggml.pre", "qwen35"),
        ] {
            if metadata.get(key).and_then(|value| value.as_str()) != Some(required) {
                return Err(invalid(format!(
                    "unsupported Qwen35 pretokenizer metadata: {key}"
                )));
            }
        }
        Ok(Self { _validated: () })
    }

    /// Splits UTF-8 into nonempty, ordered slices borrowed from the input.
    ///
    /// Concatenating the slices recovers every original byte. No special-token
    /// spelling is recognized and no bytes are normalized, inserted or removed.
    /// Empty input produces no pieces. Limits match the ranked BPE core: 1 MiB
    /// input, 65,536 pieces and 64 KiB per piece. A longer regex match is rejected
    /// rather than split, since invented boundaries would change merge results.
    ///
    /// Work is linear in input scalars with a bounded binary category lookup;
    /// storage is at most 65,536 borrowed slices and no copied input characters.
    /// Use [`Self::pieces`] to consume the same boundaries without collecting.
    ///
    /// # Errors
    /// Rejects input/piece limits and allocation failures.
    pub fn split<'a>(&self, text: &'a str) -> Result<Vec<&'a str>> {
        let boundaries = self.pieces(text)?;
        let mut pieces = Vec::new();
        pieces.try_reserve_exact(text.len().min(MAX_BPE_INPUT_PIECES))?;
        for piece in boundaries {
            pieces.push(piece?);
        }
        Ok(pieces)
    }

    /// Iterates the same borrowed boundaries as [`Self::split`] without allocating.
    ///
    /// Input length is checked immediately. Per-piece and piece-count limits
    /// are checked as pieces are consumed; finish the iterator to validate all
    /// input. An error terminates iteration. No bytes are copied or normalized.
    ///
    /// # Errors
    /// Rejects input above the byte limit. Iterator items reject piece limits.
    pub fn pieces<'a>(&self, text: &'a str) -> Result<Qwen35Pieces<'a>> {
        if text.len() > MAX_BPE_INPUT_BYTES {
            return Err(invalid("Qwen35 pretokenizer input exceeds byte limit"));
        }
        Ok(Qwen35Pieces {
            remaining: text,
            emitted: 0,
        })
    }
}

impl<'a> Iterator for Qwen35Pieces<'a> {
    type Item = Result<&'a str>;

    fn next(&mut self) -> Option<Self::Item> {
        if self.remaining.is_empty() {
            return None;
        }
        let end = piece_end(self.remaining);
        if end > MAX_BPE_PIECE_BYTES {
            self.remaining = "";
            return Some(Err(invalid("Qwen35 pretokenizer piece exceeds byte limit")));
        }
        if self.emitted == MAX_BPE_INPUT_PIECES {
            self.remaining = "";
            return Some(Err(invalid(
                "Qwen35 pretokenizer input exceeds piece limit",
            )));
        }
        let (piece, remaining) = self.remaining.split_at(end);
        self.remaining = remaining;
        self.emitted += 1;
        Some(Ok(piece))
    }
}

impl std::iter::FusedIterator for Qwen35Pieces<'_> {}

fn piece_end(text: &str) -> usize {
    let mut characters = text.char_indices();
    let Some((_, first)) = characters.next() else {
        return 0;
    };

    // The pinned lowercase table maps only ASCII capitals to the ASCII letters
    // used by these contractions; Unicode case folding would change the policy.
    if first == '\'' {
        let bytes = text.as_bytes();
        match bytes.get(1).map(u8::to_ascii_lowercase) {
            Some(b's' | b't' | b'm' | b'd') => return 2,
            Some(b'r' | b'v' | b'l') => {
                let second = bytes[1].to_ascii_lowercase();
                let third = bytes.get(2).map(u8::to_ascii_lowercase);
                if matches!(
                    (second, third),
                    (b'r' | b'v', Some(b'e')) | (b'l', Some(b'l'))
                ) {
                    return 3;
                }
            }
            _ => {}
        }
    }

    let first_category = category(first);
    if !matches!(first, '\r' | '\n')
        && first_category != NUMBER
        && (first_category == LETTER_OR_MARK
            || text[first.len_utf8()..]
                .chars()
                .next()
                .is_some_and(|character| category(character) == LETTER_OR_MARK))
    {
        let mut end = first.len_utf8();
        for (offset, character) in characters {
            if category(character) != LETTER_OR_MARK {
                break;
            }
            end = offset + character.len_utf8();
        }
        return end;
    }

    if first_category == NUMBER {
        return first.len_utf8();
    }

    let punctuation_start = usize::from(first == ' ');
    if text[punctuation_start..]
        .chars()
        .next()
        .is_some_and(is_punctuation_piece)
    {
        let mut end = punctuation_start;
        for (offset, character) in text[punctuation_start..].char_indices() {
            if !is_punctuation_piece(character) {
                break;
            }
            end = punctuation_start + offset + character.len_utf8();
        }
        for (offset, character) in text[end..].char_indices() {
            if !matches!(character, '\r' | '\n') {
                return end + offset;
            }
        }
        return text.len();
    }

    let mut whitespace_end = 0;
    let mut last_newline_end = 0;
    let mut last_whitespace_bytes = 0;
    let mut whitespace_count = 0;
    for (offset, character) in text.char_indices() {
        if !is_whitespace(character) {
            break;
        }
        whitespace_end = offset + character.len_utf8();
        last_whitespace_bytes = character.len_utf8();
        whitespace_count += 1;
        if matches!(character, '\r' | '\n') {
            last_newline_end = whitespace_end;
        }
    }
    if last_newline_end > 0 {
        return last_newline_end;
    }
    if whitespace_count > 1 && whitespace_end < text.len() {
        return whitespace_end - last_whitespace_bytes;
    }
    if whitespace_end > 0 {
        return whitespace_end;
    }
    first.len_utf8()
}

fn is_punctuation_piece(character: char) -> bool {
    category(character) == 0 && !is_whitespace(character)
}

const fn is_whitespace(character: char) -> bool {
    // Exact unicode_set_whitespace in the pinned source (25 scalar values).
    matches!(
        character,
        '\u{0009}'..='\u{000d}'
            | ' '
            | '\u{0085}'
            | '\u{00a0}'
            | '\u{1680}'
            | '\u{2000}'..='\u{200a}'
            | '\u{2028}'
            | '\u{2029}'
            | '\u{202f}'
            | '\u{205f}'
            | '\u{3000}'
    )
}

fn category(character: char) -> u8 {
    if character.is_ascii_alphabetic() {
        return LETTER_OR_MARK;
    }
    if character.is_ascii_digit() {
        return NUMBER;
    }
    if character.is_ascii() {
        return 0;
    }
    let scalar = u32::from(character);
    let index = CATEGORY_STARTS.partition_point(|&(start, _)| start <= scalar) - 1;
    CATEGORY_STARTS[index].1
}

